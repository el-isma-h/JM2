    main = terme.split(" (")[0].split(" — ")[0]
    TERMS.append({
        "terme": terme,
        "slug": slug or slugify(main),
        "cat": cat,
        "niv": niv,
        "definition": definition,
        "analogie": analogie,
        "exemple": exemple,
        "voir": list(voir),
        "motifs": motifs if motifs is not None else [re.escape(main)],
        "src": src,
    })
